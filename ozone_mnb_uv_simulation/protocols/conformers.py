"""
Part 2 conformer pool for O3.H2O (JOB-2026-0905-009).

14 initial structures, all charge 0 / singlet, built from the experimental
monomer geometries used in the Phase-1 baseline (run_baseline.ozone_geom /
water_geom) so that the pool is reproducible from a documented rule set.

Coverage:
  * H-bond donation from water to a TERMINAL ozone oxygen, along the in-plane
    lone-pair direction, along the O-O axis, and out of the ozone plane;
    near (H...O = 2.0 A) and far (2.9 A) contacts;
  * water rotating about its donating O-H axis (coplanar vs non-coplanar);
  * water O approaching the CENTRAL ozone oxygen (lone-pair contact above the
    plane, in-plane contact, and H-down bifurcated contact);
  * symmetric double donation across the two terminal oxygens;
  * side-on O_w contact with the terminal O...O edge, and a stacked
    (water plane parallel to the ozone plane) arrangement.

Atom order in every structure: O3 central, O3 terminal(+x), O3 terminal(-x),
water O, water H(donor/H1), water H(H2).

Writes inputs/o3_h2o_hydration/{c01..c14}.xyz and conformer_pool.json.
"""
import os
import json
import math
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN_DIR = os.path.join(ROOT, 'inputs', 'o3_h2o_hydration')

R_OO = 1.2717          # ozone experimental r(O-O), Angstrom
ANG_OOO = 117.79       # ozone experimental angle
R_OH = 0.9584          # water experimental r(O-H)
ANG_HOH = 104.45       # water experimental angle
HALF_HOH = math.radians(ANG_HOH / 2.0)


def ozone_frame():
    """Central O at origin, terminal O at (+/-x, +y, 0); molecular plane = xy."""
    t = math.radians(ANG_OOO / 2.0)
    return np.array([[0.0, 0.0, 0.0],
                     [R_OO * math.sin(t), R_OO * math.cos(t), 0.0],
                     [-R_OO * math.sin(t), R_OO * math.cos(t), 0.0]])


def _unit(v):
    v = np.asarray(v, dtype=float)
    return v / np.linalg.norm(v)


def _rot_z(v, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    return np.array([c * v[0] - s * v[1], s * v[0] + c * v[1], v[2]])


def _perp_basis(u, ref):
    u = _unit(u)
    ref = np.asarray(ref, dtype=float)
    e1 = ref - np.dot(ref, u) * u
    if np.linalg.norm(e1) < 1e-6:
        ref = np.array([1.0, 0.0, 0.0])
        if abs(u[0]) > 0.9:
            ref = np.array([0.0, 1.0, 0.0])
        e1 = ref - np.dot(ref, u) * u
    e1 = _unit(e1)
    e2 = np.cross(u, e1)
    return e1, e2


def _terminal_ext_inplane(frame, idx):
    """In-plane unit vector at a terminal oxygen that is perpendicular to its
    O-O bond and points to the OUTSIDE of the O3 framework (verified: no atom
    of the approach corridor is within 1.7 A of any ozone atom)."""
    bond = _unit(frame[0] - frame[idx])            # terminal O -> central O
    n = np.array([-bond[1], bond[0], 0.0])         # in-plane perpendicular
    probe = frame[idx] + 2.0 * n
    dmin = min(np.linalg.norm(probe - frame[i]) for i in range(3))
    if dmin < 1.9:                                 # pointing inside the V: flip it
        n = -n
    return _unit(n)


def dir_vector(name, frame):
    """Named approach directions resolved in the ozone frame.

    frame[0] = central O, frame[1] = terminal O (+x), frame[2] = terminal O (-x).
    All terminal-oxygen directions point to the exterior of the framework.
    """
    w_r = _unit(frame[1] - frame[0])          # central -> terminal(+x)
    z = np.array([0.0, 0.0, 1.0])
    mid23 = 0.5 * (frame[1] + frame[2])
    ext_r = _terminal_ext_inplane(frame, 1)   # exterior in-plane at terminal O(+x)
    ext_l = _terminal_ext_inplane(frame, 2)   # exterior in-plane at terminal O(-x)
    d = {
        # --- terminal O (+x, frame[1])
        'axis': w_r,                             # along the O-O bond extension (linear)
        'ext_inplane': ext_r,                    # in-plane, perpendicular, exterior
        'perp': z,                               # perpendicular to the ozone plane
        'perp_neg': -z,
        'tilt_up': _unit(ext_r + z),             # between in-plane-exterior and +z
        'tilt_down': _unit(ext_r - z),
        'tilt_axis': _unit(w_r + z),
        # --- terminal O (-x, frame[2]): mirror images
        'axis_L': _unit(frame[2] - frame[0]),
        'ext_inplane_L': ext_l,
        # --- central O / molecular centre
        'cent_out': _unit(mid23 - frame[0]),     # in-plane, central O -> O-O edge
        'cent_out_neg': -_unit(mid23 - frame[0]),  # in-plane, opposite (open) side
        'cent_z': z,
    }
    if name not in d:
        raise KeyError('unknown direction %r' % name)
    return d[name]


def place_h_donor(anchor, u, d, phi_deg, ref):
    """Water donates H1: H1 sits d (Angstrom) from the anchor along u, O_w lies
    further out on the same axis (linear O_w-H...O).  H2 is generated by the
    H-O-H angle and a rotation phi about the O_w->H1 axis."""
    u = _unit(u)
    h1 = np.asarray(anchor, dtype=float) + d * u
    ow = h1 + R_OH * u                    # O_w is beyond H1, away from the anchor
    e1, e2 = _perp_basis(u, ref)
    phi = math.radians(phi_deg)
    th = math.radians(ANG_HOH)
    v2 = math.cos(th) * (-u) + math.sin(th) * (math.cos(phi) * e1 + math.sin(phi) * e2)
    h2 = ow + R_OH * v2
    return np.array([ow, h1, h2])


def place_o_contact(anchor, u, d, b_vec, e_vec):
    """Water O sits d (Angstrom) from the anchor along u; the water bisector
    points along b_vec and the H-H axis along e_vec (orthogonalised vs b)."""
    u = _unit(u)
    ow = np.asarray(anchor, dtype=float) + d * u
    b = _unit(np.asarray(b_vec, dtype=float))
    e = np.asarray(e_vec, dtype=float)
    e = e - np.dot(e, b) * b
    if np.linalg.norm(e) < 1e-6:
        e = _perp_basis(b, [0.0, 0.0, 1.0])[0]
    e = _unit(e)
    h1 = ow + R_OH * (math.cos(HALF_HOH) * b + math.sin(HALF_HOH) * e)
    h2 = ow + R_OH * (math.cos(HALF_HOH) * b - math.sin(HALF_HOH) * e)
    return np.array([ow, h1, h2])


def resolve_anchor(anchor, frame):
    if isinstance(anchor, int):
        return frame[anchor], 'atom %d (%s)' % (
            anchor, 'central O' if anchor == 0 else 'terminal O')
    if anchor == 'mid23':
        return 0.5 * (frame[1] + frame[2]), 'midpoint of the two terminal O'
    if anchor == 'centroid':
        return frame.mean(axis=0), 'geometric centroid of O3'
    raise ValueError(anchor)


