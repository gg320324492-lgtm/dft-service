def build(spec, frame=None):
    frame = ozone_frame() if frame is None else frame
    anchor, anchor_desc = resolve_anchor(spec['anchor'], frame)
    u = dir_vector(spec['u'], frame)
    if spec['mode'] == 'h_donor':
        water = place_h_donor(anchor, u, spec['d'], spec['phi'], spec['ref'])
    else:
        b = spec['b']
        if b == '+u':
            b_vec = u
        elif b == '-u':
            b_vec = -u
        elif b == '+x':
            b_vec = np.array([1.0, 0.0, 0.0])
        elif b == '+y':
            b_vec = np.array([0.0, 1.0, 0.0])
        else:
            b_vec = np.asarray(b, dtype=float)
        water = place_o_contact(anchor, u, spec['d'], b_vec, spec['e'])
    coords = np.vstack([frame, water])
    return coords


def write_xyz(path, coords):
    syms = ['O', 'O', 'O', 'O', 'H', 'H']
    lines = [str(len(syms)), 'O3-H2O initial conformer (Angstrom)']
    for s, c in zip(syms, coords):
        lines.append('%-2s %18.10f %18.10f %18.10f' % (s, c[0], c[1], c[2]))
    with open(path, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')


def main():
    os.makedirs(IN_DIR, exist_ok=True)
    frame = ozone_frame()
    pool = []
    for spec in SPECS:
        coords = build(spec, frame)
        spec_out = dict(spec)
        spec_out['anchor_description'] = resolve_anchor(spec['anchor'], frame)[1]
        spec_out['u_vector'] = [round(float(x), 6) for x in dir_vector(spec['u'], frame)]
        spec_out['initial_coords_angstrom'] = [
            [round(float(x), 8) for x in row] for row in coords]
        pool.append(spec_out)
        write_xyz(os.path.join(IN_DIR, '%s.xyz' % spec['id']), coords)
    manifest = dict(
        job='JOB-2026-0905-009',
        purpose='O3.H2O initial conformer pool for the Phase-2A gas-phase search',
        n_conformers=len(pool),
        charge=0, multiplicity=1,
        atom_order='O3 central, O3 terminal(+x), O3 terminal(-x), water O, water H1, water H2',
        monomer_geometries=dict(
            ozone='experimental gas phase r(O-O)=%.4f A, angle=%.2f deg' % (R_OO, ANG_OOO),
            water='experimental gas phase r(O-H)=%.4f A, angle=%.2f deg' % (R_OH, ANG_HOH)),
        placement_rules=dict(
            h_donor='H1 placed d (A) from the anchor along u, O_w further out on the '
                    'same axis; H2 from the H-O-H angle and a rotation phi about O_w->H1',
            o_contact='water O placed d (A) from the anchor along u; bisector along b, '
                      'H-H axis along e (orthogonalised against b)'),
        conformers=pool)
    path = os.path.join(IN_DIR, 'conformer_pool.json')
    with open(path, 'w') as fh:
        json.dump(manifest, fh, indent=2)
    print('wrote %d conformers -> %s' % (len(pool), IN_DIR))
    print('manifest: %s' % path)


if __name__ == '__main__':
    main()
